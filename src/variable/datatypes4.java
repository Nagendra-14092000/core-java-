package variable;

public class datatypes4 {
	
byte b;//default value=0
short s;
int i;
long l;

float f;//default value=0.0
double d;

char c  ;//default value=space
boolean bo; //default value=false
String st;//default value=null
Byte by;

public static void main(String[] args) {
	datatypes4 dt4=new datatypes4();
	System.out.println(dt4.b);
	System.out.println(dt4.s);
	System.out.println(dt4.i);
	System.out.println(dt4.l);
	System.out.println(dt4.f);
	System.out.println(dt4.d);
	System.out.println(dt4.c);
	System.out.println(dt4.bo);
	System.out.println(dt4.st);
	System.out.println(dt4.by);
}

}
